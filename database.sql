CREATE TABLE mahasiswa (
  id_mahasiswa INT AUTO_INCREMENT PRIMARY KEY,
  nim VARCHAR(20) NOT NULL UNIQUE,
  nama VARCHAR(100) NOT NULL,
  jk CHAR(1) NOT NULL DEFAULT 'L',
  prodi VARCHAR(100) NOT NULL,
  fakultas VARCHAR(100) NOT NULL,
  semester TINYINT NOT NULL DEFAULT 1
) ENGINE=InnoDB;

CREATE TABLE asesmen (
  id_asesmen INT AUTO_INCREMENT PRIMARY KEY,
  id_mahasiswa INT NOT NULL,
  tanggal DATE NOT NULL,
  phq9 TINYINT NOT NULL CHECK (phq9 BETWEEN 0 AND 27),
  gad7 TINYINT NOT NULL CHECK (gad7 BETWEEN 0 AND 21),
  stres TINYINT NOT NULL CHECK (stres BETWEEN 0 AND 10),
  jam_tidur DECIMAL(3,1) NOT NULL,
  dukungan TINYINT NOT NULL CHECK (dukungan BETWEEN 0 AND 10),
  item9 TINYINT NOT NULL DEFAULT 0,
  item_phq VARCHAR(30) NULL,
  item_gad VARCHAR(30) NULL,
  catatan VARCHAR(255) NULL,
  INDEX (tanggal),
  FOREIGN KEY (id_mahasiswa) REFERENCES mahasiswa(id_mahasiswa) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE bobot (
  kriteria VARCHAR(10) PRIMARY KEY,
  label VARCHAR(40) NOT NULL,
  bobot TINYINT NOT NULL
) ENGINE=InnoDB;

